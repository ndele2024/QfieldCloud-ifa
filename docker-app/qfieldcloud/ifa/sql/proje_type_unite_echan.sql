-- =============================================================================
--  proje_type_unite_echan — types d'UE prévus par un projet de sondage
-- =============================================================================
--  Association plusieurs-à-plusieurs entre `proje_sonda` et `type_unite_echan` :
--  un projet prévoit plusieurs types d'UE, un type d'UE se retrouve dans
--  plusieurs projets. Chaque association porte ce que le projet planifie pour
--  ce type, et les deux nombres sont obligatoires :
--    * le nombre d'implantations (au moins une) ;
--    * le nombre de remesurages (zéro ou plus).
--
--  Écrite par « Créer un projet » (plugin QField, point d'accès
--  `POST /api/v1/ifa/projets-sondage/`, voir `projet_sonda.py`).
--
--  À appliquer une fois sur une base existante. Idempotent : peut être rejoué.
--  Sur une base recréée de zéro, la table vient de `complement_sql_projet.sql`
--  (sans `qgis_id`) : rejouer ensuite ce script pour l'ajouter.
--
--      psql "service=pg_service_server" -v ON_ERROR_STOP=1 \
--           -f proje_type_unite_echan.sql
--
--  Puis donner le droit d'écriture au compte du serveur QFieldCloud
--  (VALIDATION_PG_USER) — à adapter :
--
--      GRANT SELECT, INSERT, UPDATE, DELETE
--          ON ifa_data.proje_type_unite_echan TO ifauser;
--
--  UPDATE et DELETE servent « Modifier / Supprimer un projet »
--  (`projet_gestion.py`).
--
--  Annulation :
--      DROP TABLE ifa_data.proje_type_unite_echan;
--      DROP TABLE ifa_structure.proje_type_unite_echan;
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
--  ifa_data — la table que le serveur alimente
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ifa_data.proje_type_unite_echan (
    pro_code_ident          VARCHAR(40)   NOT NULL,
    tue_code_ident          VARCHAR(40)   NOT NULL,
    ptu_nb_impla_plani      INTEGER       NOT NULL,
    ptu_nb_remes_plani      INTEGER       NOT NULL,
    ptu_date_creat          TIMESTAMP,
    ptu_code_utili_creat    VARCHAR(20),
    ptu_date_maj            TIMESTAMP,
    ptu_code_utili_maj      VARCHAR(20),
    CONSTRAINT pk_proje_type_unite_echan
        PRIMARY KEY (pro_code_ident, tue_code_ident),
    CONSTRAINT fk_ptu_pro FOREIGN KEY (pro_code_ident)
        REFERENCES ifa_data.proje_sonda (pro_code_ident),
    CONSTRAINT fk_ptu_tue FOREIGN KEY (tue_code_ident)
        REFERENCES ifa_data.type_unite_echan (tue_code_ident),
    CONSTRAINT ck_ptu_nb_impla_plani CHECK (ptu_nb_impla_plani >= 1),
    CONSTRAINT ck_ptu_nb_remes_plani CHECK (ptu_nb_remes_plani >= 0)
);

-- « Quels projets prévoient ce type ? » : la clé primaire commence par le
-- projet, elle ne sert pas cette question.
CREATE INDEX IF NOT EXISTS proje_type_unite_echan_tue_idx
    ON ifa_data.proje_type_unite_echan (tue_code_ident);

-- Colonne technique `qgis_id`, comme les 37 tables du projet QField (voir
-- `add_qgis_id.sql` et `fix_qgis_id_insert.sql`) : clé mono-colonne exigée par
-- libqfieldsync si la table devient un jour une couche hors ligne.
ALTER TABLE ifa_data.proje_type_unite_echan
    ADD COLUMN IF NOT EXISTS qgis_id BIGINT GENERATED BY DEFAULT AS IDENTITY;

CREATE UNIQUE INDEX IF NOT EXISTS proje_type_unite_echan_qgis_id_uidx
    ON ifa_data.proje_type_unite_echan (qgis_id);

DO $$
BEGIN
    IF to_regproc('ifa_qfield.qgis_id_defaut') IS NOT NULL THEN
        DROP TRIGGER IF EXISTS trg_qgis_id ON ifa_data.proje_type_unite_echan;
        CREATE TRIGGER trg_qgis_id
            BEFORE INSERT ON ifa_data.proje_type_unite_echan
            FOR EACH ROW EXECUTE FUNCTION ifa_qfield.qgis_id_defaut();
    END IF;
END $$;

COMMENT ON TABLE ifa_data.proje_type_unite_echan IS
    'Types d''unité d''échantillonnage prévus par un projet de sondage (N:M).';
COMMENT ON COLUMN ifa_data.proje_type_unite_echan.ptu_nb_impla_plani IS
    'Nombre d''implantations planifiées pour ce type dans le projet (au moins 1).';
COMMENT ON COLUMN ifa_data.proje_type_unite_echan.ptu_nb_remes_plani IS
    'Nombre de remesurages planifiés pour ce type dans le projet (0 ou plus).';

-- -----------------------------------------------------------------------------
--  ifa_structure — même structure, comme pour toutes les tables du schéma
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ifa_structure.proje_type_unite_echan (
    pro_code_ident          VARCHAR(40)   NOT NULL,
    tue_code_ident          VARCHAR(40)   NOT NULL,
    ptu_nb_impla_plani      INTEGER       NOT NULL,
    ptu_nb_remes_plani      INTEGER       NOT NULL,
    ptu_date_creat          TIMESTAMP,
    ptu_code_utili_creat    VARCHAR(20),
    ptu_date_maj            TIMESTAMP,
    ptu_code_utili_maj      VARCHAR(20),
    CONSTRAINT pk_proje_type_unite_echan
        PRIMARY KEY (pro_code_ident, tue_code_ident),
    CONSTRAINT fk_ptu_pro FOREIGN KEY (pro_code_ident)
        REFERENCES ifa_structure.proje_sonda (pro_code_ident),
    CONSTRAINT fk_ptu_tue FOREIGN KEY (tue_code_ident)
        REFERENCES ifa_structure.type_unite_echan (tue_code_ident),
    CONSTRAINT ck_ptu_nb_impla_plani CHECK (ptu_nb_impla_plani >= 1),
    CONSTRAINT ck_ptu_nb_remes_plani CHECK (ptu_nb_remes_plani >= 0)
);

COMMIT;
