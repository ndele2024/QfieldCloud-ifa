"""Création d'une unité d'échantillonnage dans la base métier.

« Créer une UE » ne se contente pas de préparer un projet : la nouvelle unité
est **inscrite dans `ifa_data.unite_echan` et verrouillée** avant même que le
technicien ne parte sur le terrain. C'est ce qui réserve son code : l'identifiant
est composé de la région, du n° de plan d'eau et du type d'UE, et deux équipes
qui visent le même plan d'eau le même jour composeraient le même. Le verrou dit
qui l'a réservé, et pourquoi.

C'est la deuxième écriture que QFieldCloud pratique sur la base du ministère,
après le verrouillage de `verrou.py`. Le compte PostgreSQL du serveur a donc
besoin du droit `INSERT` sur `unite_echan`, en plus de l'`UPDATE`.

---------------------------------------------------------------------------
CE QUI EST ÉCRIT
---------------------------------------------------------------------------
    une_code_ident        l'identifiant composé par la fenêtre
    tue_code_ident        le type, résolu par son libellé (clé étrangère)
    une_ind_verro         'O' — l'unité est tenue dès sa création
    une_nom_propr_verro   l'utilisateur QFieldCloud
    une_date_verro        maintenant
    une_raiso_verro       RAISON_CREATION
    une_date_creat        maintenant
    une_code_utili_creat  l'utilisateur
    une_date_maj          maintenant
    une_code_utili_maj    l'utilisateur

`qgis_id` n'est pas fournie : c'est une colonne d'identité
(`GENERATED BY DEFAULT`, voir `fix_qgis_id_insert.sql`), PostgreSQL la remplit.
Les autres colonnes (`une_com`, `une_code_ident_origi`, `une_ind_fichi_lier`)
restent nulles — elles appartiennent à la saisie, qui n'a pas encore eu lieu.

---------------------------------------------------------------------------
REPRENDRE SA PROPRE CRÉATION
---------------------------------------------------------------------------
L'unité est créée **avant** la préparation du projet, qui peut échouer — un
packaging refusé, une liaison coupée. Plutôt que de supprimer la ligne (ce qui
demanderait un droit `DELETE` sur la base du ministère pour un cas de
rattrapage), une seconde tentative sur le même code **reprend** la création :
la ligne existe, elle est tenue par le même utilisateur, avec la raison de
création — c'est la sienne, il peut continuer.

Un code tenu par quelqu'un d'autre, ou qui porte déjà des inventaires, ressort
en revanche en `UniteExistanteError` : c'est une unité du fonds, pas une reprise.
"""

from __future__ import annotations

import logging
from typing import Any

from qfieldcloud.ifa import db, verrou
from qfieldcloud.ifa.exceptions import (
    FiltreInvalideError,
    TypeUniteIntrouvableError,
    UniteExistanteError,
)

logger = logging.getLogger(__name__)

# La raison du verrou posé à la création. Elle est fixe : ce n'est pas un motif
# que le technicien choisit, c'est l'état de l'unité — réservée, pas encore
# inventoriée. C'est aussi elle qui permet de reconnaître une reprise.
RAISON_CREATION = "nouvelle Unité d'échantillonnage"

# Longueurs déclarées dans le schéma hérité.
LONGUEUR_CODE = 40
LONGUEUR_TYPE_NOM = 100


def creer(une_code_ident: str, type_nom: str, utilisateur: str) -> dict[str, Any]:
    """Inscrit la nouvelle unité et la verrouille. Rend son état de verrou."""
    code = (une_code_ident or "").strip()

    if not code:
        raise FiltreInvalideError("L'identifiant de la nouvelle unité est absent.")

    if len(code) > LONGUEUR_CODE:
        raise FiltreInvalideError(
            f"L'identifiant « {code} » dépasse {LONGUEUR_CODE} caractères.",
        )

    tue_code_ident = type_par_nom(type_nom)
    schema = db.schema()

    with db.curseur_ecriture() as cur:
        cur.execute(
            f"""
            INSERT INTO {schema}.unite_echan (
                une_code_ident, tue_code_ident,
                une_ind_verro, une_nom_propr_verro,
                une_date_verro, une_raiso_verro,
                une_date_creat, une_code_utili_creat,
                une_date_maj, une_code_utili_maj
            )
            VALUES (
                %(code)s, %(type)s,
                %(tenue)s, %(proprietaire)s,
                LOCALTIMESTAMP, %(raison)s,
                LOCALTIMESTAMP, %(utilisateur)s,
                LOCALTIMESTAMP, %(utilisateur)s
            )
            ON CONFLICT (une_code_ident) DO NOTHING
            """,
            {
                "code": code,
                "type": tue_code_ident,
                "tenue": verrou.TENUE,
                "proprietaire": utilisateur[: verrou.LONGUEUR_PROPRIETAIRE],
                "raison": RAISON_CREATION,
                "utilisateur": utilisateur[: verrou.LONGUEUR_UTILISATEUR],
            },
        )
        creee = cur.rowcount == 1

    if creee:
        logger.info("[IFA] unite %s creee et verrouillee par %s", code, utilisateur)
        return verrou.lire(code)

    return _reprendre(code, utilisateur)


def _reprendre(code: str, utilisateur: str) -> dict[str, Any]:
    """Le code existe déjà : est-ce une reprise, ou une unité du fonds ?"""
    unite = verrou.lire(code)

    sienne = unite["une_nom_propr_verro"] == utilisateur[: verrou.LONGUEUR_PROPRIETAIRE]

    if (
        unite["une_ind_verro"] == verrou.TENUE
        and sienne
        and unite["une_raiso_verro"] == RAISON_CREATION
    ):
        logger.info("[IFA] creation de %s reprise par %s", code, utilisateur)
        return unite

    if verrou.tenue_par_un_autre(unite, utilisateur):
        raise UniteExistanteError(
            "L'unité {code} existe déjà et elle est verrouillée par {qui}. "
            "Modifiez l'identifiant pour en créer une autre.".format(
                code=code,
                qui=unite["une_nom_propr_verro"] or "un autre utilisateur",
            ),
        )

    raise UniteExistanteError(
        f"L'unité {code} existe déjà dans la base IFA. Modifiez l'identifiant "
        "pour en créer une autre, ou ouvrez celle-ci depuis « Consulter une UE ».",
    )


def type_par_nom(nom: str) -> str:
    """Identifiant du type d'UE, retrouvé par son libellé.

    La fenêtre envoie le libellé (« Inventaire sur plan d'eau ») et non
    l'identifiant : sa liste de types est encore codée en dur, et ce sont les
    libellés qui y sont écrits. Ils correspondent un à un à `tue_nom`.

    La comparaison ignore la casse et les espaces de bordure, mais pas les
    accents : `tue_nom` les porte, et le plugin les écrit.
    """
    libelle = (nom or "").strip()

    if not libelle:
        raise TypeUniteIntrouvableError(
            "Le type de la nouvelle unité d'échantillonnage n'est pas précisé.",
        )

    schema = db.schema()

    with db.curseur() as cur:
        cur.execute(
            f"""
            SELECT tue_code_ident
              FROM {schema}.type_unite_echan
             WHERE lower(btrim(tue_nom)) = lower(%s)
             ORDER BY tue_code_ident
             LIMIT 1
            """,
            [libelle[:LONGUEUR_TYPE_NOM]],
        )
        ligne = cur.fetchone()

    if ligne is None:
        raise TypeUniteIntrouvableError(
            f"Le type d'UE « {libelle} » n'existe pas dans la base IFA.",
        )

    return ligne[0]
