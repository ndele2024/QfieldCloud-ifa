"""Création d'un projet de sondage dans la base métier.

« Créer un projet » inscrit une ligne dans `ifa_data.proje_sonda`, et les types
d'UE que le projet prévoit dans `ifa_data.proje_type_unite_echan`. Rien d'autre :
pas de projet QFieldCloud à préparer, pas de packaging à attendre. Le projet de
sondage est une entrée de référentiel — c'est à lui que les mesurages des unités
seront rattachés (`mesurage.pro_code_ident`), et c'est sa région (`rad_no`) qui
fait foi pour la recherche par région (voir `filtres._predicat_region`).

C'est la troisième écriture que QFieldCloud pratique sur la base du ministère,
après le verrouillage (`verrou.py`) et la création d'une unité (`unite.py`). Le
compte PostgreSQL du serveur a donc besoin du droit `INSERT` sur `proje_sonda`
et sur `proje_type_unite_echan` (table créée par
`sql/proje_type_unite_echan.sql`).

---------------------------------------------------------------------------
CE QUI EST ÉCRIT
---------------------------------------------------------------------------
    pro_code_ident              un UUID, comme tout le fonds hérité
    pro_no, pro_nom, pro_an     saisis dans la fenêtre
    rad_no                      saisie — valeur du type énuméré `region`
    pro_code_statu              saisi : « El » (élaboration) ou « Pr »
    pro_date_statu              maintenant
    pro_date_premi_mise_produ   maintenant si le projet naît en production
    pro_ind_inven_norma         'O' / 'N'
    pro_descr, pro_com          saisis, facultatifs
    vet_code_ident              la version du type « Type Projet » — voir
                                `version_projet`
    pro_date_creat / _maj       maintenant
    pro_code_utili_creat / _maj l'utilisateur QFieldCloud

`qgis_id` n'est pas fournie : colonne d'identité `GENERATED BY DEFAULT`
(voir `fix_qgis_id_insert.sql`), PostgreSQL la remplit.

---------------------------------------------------------------------------
LES TYPES D'UE DU PROJET
---------------------------------------------------------------------------
Un projet prévoit un ou plusieurs types d'UE, et un type d'UE se retrouve dans
plusieurs projets : l'association plusieurs-à-plusieurs vit dans
`proje_type_unite_echan`, une ligne par couple (projet, type), avec ce que le
projet planifie pour ce type — les deux nombres sont obligatoires :

    pro_code_ident, tue_code_ident   le couple — clé primaire
    ptu_nb_impla_plani               nombre d'implantations planifiées (≥ 1)
    ptu_nb_remes_plani               nombre de remesurages planifiés (≥ 0)
    ptu_date_creat / _maj, ptu_code_utili_creat / _maj

Ajouter un type à un projet, c'est dire combien d'implantations et de
remesurages on y planifie : un type sans ces deux nombres n'est pas planifié.
Au moins une implantation — un type sans implantation n'aurait rien à faire
dans le projet —, et zéro remesurage ou plus : une campagne unique n'en
prévoit pas.

Le projet et ses types sont écrits dans la **même transaction** : un type
inconnu annule aussi le projet, plutôt que de laisser un projet sans les types
qu'on a voulu lui donner.

Les types voyagent par leur identifiant (`tue_code_ident`), tel que
`types_disponibles()` les a rendus au plugin — pas par leur libellé, que la
liste codée en dur du plugin ne connaît pas tous. « Type Projet » n'en fait pas
partie : c'est le type qui qualifie les projets eux-mêmes, pas un type d'UE
qu'un projet prévoirait.

---------------------------------------------------------------------------
LE NUMÉRO DE PROJET EST UNIQUE
---------------------------------------------------------------------------
La base ne le garantit pas — la clé primaire est l'UUID — mais le fonds le
respecte : aucun des 166 projets hérités ne partage son `pro_no`. C'est aussi
lui que le plugin transporte comme `code_projet` d'une unité créée. Deux projets
au même numéro rendraient ce rattachement ambigu.

L'unicité est donc vérifiée ici, à la casse et aux espaces de bordure près, sous
un verrou consultatif de transaction : deux créations simultanées du même numéro
ne passent pas toutes les deux entre la vérification et l'`INSERT`.
"""

