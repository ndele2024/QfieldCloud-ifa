def types_disponibles() -> list[dict[str, str]]:
    """Les types d'UE qu'un projet peut prévoir, triés par libellé.

    Lus dans `type_unite_echan`, sans « Type Projet ». La liste du plugin
    (`Referentiels.typesUe`) est codée en dur et en omet plusieurs (ADNe,
    Enregistrement saumon atlantique…) : c'est celle-ci qui fait foi pour
    l'association.
    """
    schema = db.schema()

    with db.curseur() as cur:
        cur.execute(
            f"""
            SELECT tue_code_ident, btrim(tue_nom) AS tue_nom, tue_descr
              FROM {schema}.type_unite_echan
             WHERE nullif(btrim(tue_nom), '') IS NOT NULL
               AND lower(btrim(tue_nom)) <> lower(%s)
             ORDER BY lower(btrim(tue_nom))
            """,
            [TYPE_PROJET_NOM],
        )
        lignes = db.lignes_en_dictionnaires(cur)

    return [
        {
            "tue_code_ident": _texte(ligne["tue_code_ident"]),
            "tue_nom": _texte(ligne["tue_nom"]),
            "tue_descr": _texte(ligne["tue_descr"]),
        }
        for ligne in lignes
    ]


def types_du_projet(pro_no: str) -> dict[str, Any]:
    """Les types d'UE que prévoit un projet, désigné par son n°.

    Sert « Créer une UE » : la liste des types y est restreinte à ceux du
    projet choisi. Un projet sans type associé — les 166 projets hérités, qui
    précèdent `proje_type_unite_echan` — rend une liste vide, et le plugin
    propose alors tous les types.

    Le projet se désigne par son n° parce que c'est ce que porte la liste du
    plugin (lue dans la couche `proje_sonda`) ; la comparaison ignore la casse,
    comme l'unicité vérifiée à la création.
    """
    numero = (pro_no or "").strip()

    if not numero:
        raise FiltreInvalideError("Le n° du projet est absent.")

    if len(numero) > LONGUEUR_NUMERO:
        raise FiltreInvalideError(
            f"Le n° du projet ne peut pas dépasser {LONGUEUR_NUMERO} caractères.",
        )

    schema = db.schema()

    with db.curseur() as cur:
        projet = projet_par_numero(cur, schema, numero)

        if projet is None:
            raise ProjetIntrouvableError(
                f"Aucun projet de sondage ne porte le n° « {numero} ».",
            )

        types = types_associes(cur, schema, projet["pro_code_ident"])

    return {
        "pro_code_ident": _texte(projet["pro_code_ident"]),
        "pro_no": _texte(projet["pro_no"]),
        "pro_nom": _texte(projet["pro_nom"]),
        "types": types,
    }


def types_associes(cur: Any, schema: str, pro_code_ident: str) -> list[dict[str, Any]]:
    """Les types d'UE associés à un projet, normalisés, triés par libellé."""
    cur.execute(
        f"""
        SELECT a.tue_code_ident, btrim(t.tue_nom) AS tue_nom,
               a.ptu_nb_impla_plani, a.ptu_nb_remes_plani
          FROM {schema}.proje_type_unite_echan a
          JOIN {schema}.type_unite_echan t
            ON t.tue_code_ident = a.tue_code_ident
         WHERE a.pro_code_ident = %s
         ORDER BY lower(btrim(t.tue_nom))
        """,
        [pro_code_ident],
    )

    return [
        normaliser_type(
            {
                "tue_code_ident": ligne["tue_code_ident"],
                "nb_impla_plani": ligne["ptu_nb_impla_plani"],
                "nb_remes_plani": ligne["ptu_nb_remes_plani"],
            },
            _texte(ligne["tue_nom"]),
        )
        for ligne in db.lignes_en_dictionnaires(cur)
    ]


def creer(donnees: dict[str, Any], utilisateur: str) -> dict[str, Any]:
    """Inscrit le projet et ses types d'UE. Rend le projet écrit, normalisé.

    `donnees` est la sortie validée de `ProjetSondageSerializer` : les
    longueurs, l'année, la région, le statut et la forme des types (au moins
    un, sans doublon) y ont déjà été vérifiés. Reste à vérifier ce que seule la
    base sait : le n° est-il libre, les types existent-ils.
    """
    schema = db.schema()
    numero = donnees["pro_no"]
    statut = donnees["pro_code_statu"]
    types_demandes = donnees.get("types_ue") or []
    code_utilisateur = utilisateur[: verrou.LONGUEUR_UTILISATEUR]

    with db.curseur_ecriture() as cur:
        cur.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", [CLE_VERROU_NUMERO])

        existant = projet_par_numero(cur, schema, numero)
        if existant is not None:
            raise ProjetExistantError(
                "Le n° de projet « {numero} » est déjà porté par le projet "
                "« {nom} » ({an}). Choisissez un autre numéro.".format(
                    numero=numero,
                    nom=existant["pro_nom"] or existant["pro_no"],
                    an=existant["pro_an"] or "année inconnue",
                ),
            )

        # Avant le premier `INSERT` : un type inconnu ne doit rien laisser.
        noms_types = noms_des_types(
            cur, schema, [t["tue_code_ident"] for t in types_demandes]
        )

        cur.execute(
            f"""
            INSERT INTO {schema}.proje_sonda (
                pro_code_ident, pro_no, pro_nom, pro_an, rad_no,
                pro_descr, pro_com,
                pro_code_statu, pro_date_statu, pro_date_premi_mise_produ,
                pro_ind_inven_norma, vet_code_ident,
                pro_date_creat, pro_code_utili_creat,
                pro_date_maj, pro_code_utili_maj
            )
            VALUES (
                %(code)s, %(numero)s, %(nom)s, %(an)s, %(region)s,
                %(description)s, %(commentaire)s,
                %(statut)s, LOCALTIMESTAMP,
                CASE WHEN %(en_production)s THEN LOCALTIMESTAMP END,
                %(normalise)s, %(version)s,
                LOCALTIMESTAMP, %(utilisateur)s,
                LOCALTIMESTAMP, %(utilisateur)s
            )
            RETURNING
                pro_code_ident, pro_no, pro_nom, pro_an, rad_no,
                pro_descr, pro_com, pro_code_statu, pro_date_statu,
                pro_date_premi_mise_produ, pro_ind_inven_norma,
                pro_date_creat, pro_code_utili_creat
            """,
            {
                "code": str(uuid.uuid4()),
                "numero": numero,
                "nom": donnees["pro_nom"],
                "an": donnees["pro_an"],
                "region": donnees["rad_no"],
                # Une chaîne vide n'est pas une description : NULL, comme le
                # reste du fonds.
                "description": donnees.get("pro_descr") or None,
                "commentaire": donnees.get("pro_com") or None,
                "statut": statut,
                "en_production": statut == STATUT_PRODUCTION,
                "normalise": OUI if donnees.get("pro_ind_inven_norma") else NON,
                "version": version_projet(cur, schema),
                "utilisateur": code_utilisateur,
            },
        )
        ligne = db.lignes_en_dictionnaires(cur)[0]

        types_ecrits = associer_types(
            cur, schema, ligne["pro_code_ident"], types_demandes, code_utilisateur
        )

    logger.info(
        "[IFA] projet %s (%s) cree par %s avec %s type(s) d'UE",
        ligne["pro_no"],
        ligne["pro_code_ident"],
        code_utilisateur,
        len(types_ecrits),
    )

    projet = normaliser(ligne)
    projet["types_ue"] = [
        normaliser_type(t, noms_types.get(t["tue_code_ident"], ""))
        for t in types_ecrits
    ]
    return projet


def noms_des_types(cur: Any, schema: str, codes: list[str]) -> dict[str, str]:
    """Libellé de chacun des types demandés. Lève si l'un d'eux est inconnu.

    « Type Projet » est traité en inconnu : il existe dans le référentiel, mais
    ce n'est pas un type qu'un projet prévoit.
    """
    if not codes:
        return {}

    cur.execute(
        f"""
        SELECT tue_code_ident, btrim(tue_nom) AS tue_nom
          FROM {schema}.type_unite_echan
         WHERE tue_code_ident = ANY(%s)
           AND lower(btrim(coalesce(tue_nom, ''))) <> lower(%s)
        """,
        [list(codes), TYPE_PROJET_NOM],
    )
    noms = {code: _texte(nom) for code, nom in cur.fetchall()}

    inconnus = [code for code in codes if code not in noms]
    if inconnus:
        raise TypeUniteIntrouvableError(
            "Type(s) d'UE inconnu(s) de la base IFA : {codes}. Rechargez la "
            "liste des types et recommencez.".format(codes=", ".join(inconnus)),
        )

    return noms


def associer_types(
    cur: Any,
    schema: str,
    pro_code_ident: str,
    types_demandes: list[dict[str, Any]],
    code_utilisateur: str,
) -> list[dict[str, Any]]:
    """Écrit une ligne de `proje_type_unite_echan` par type. Rend ce qui est écrit."""
    ecrits = []

    for demande in types_demandes:
        cur.execute(
            f"""
            INSERT INTO {schema}.proje_type_unite_echan (
                pro_code_ident, tue_code_ident,
                ptu_nb_impla_plani, ptu_nb_remes_plani,
                ptu_date_creat, ptu_code_utili_creat,
                ptu_date_maj, ptu_code_utili_maj
            )
            VALUES (
                %(projet)s, %(type)s,
                %(implantations)s, %(remesurages)s,
                LOCALTIMESTAMP, %(utilisateur)s,
                LOCALTIMESTAMP, %(utilisateur)s
            )
            """,
            {
                "projet": pro_code_ident,
                "type": demande["tue_code_ident"],
                "implantations": demande["nb_impla_plani"],
                "remesurages": demande["nb_remes_plani"],
                "utilisateur": code_utilisateur,
            },
        )
        ecrits.append(demande)

    return ecrits


def projet_par_numero(cur: Any, schema: str, numero: str) -> dict[str, Any] | None:
    """Le projet qui porte déjà ce numéro, à la casse près, ou None."""
    cur.execute(
        f"""
        SELECT pro_code_ident, pro_no, pro_nom, pro_an
          FROM {schema}.proje_sonda
         WHERE lower(btrim(pro_no)) = lower(btrim(%s))
         LIMIT 1
        """,
        [numero],
    )
    lignes = db.lignes_en_dictionnaires(cur)
    return lignes[0] if lignes else None


def version_projet(cur: Any, schema: str) -> str:
    """La version de type qui qualifie un projet de sondage.

    `IFA_PROJET_VERSION_TYPE` la désigne si l'administrateur l'a fixée. Sinon,
    c'est la version en production du type « Type Projet » ; s'il y en a
    plusieurs, celle que portent déjà le plus de projets — le nouveau projet
    ressemble ainsi au fonds plutôt qu'à une version qu'on vient d'ajouter.
    """
    configuree = (getattr(settings, "IFA_PROJET_VERSION_TYPE", "") or "").strip()
    if configuree:
        return configuree

    cur.execute(
        f"""
        SELECT v.vet_code_ident
          FROM {schema}.versi_type_unite_echan v
          JOIN {schema}.type_unite_echan t ON t.tue_code_ident = v.tue_code_ident
         WHERE lower(btrim(t.tue_nom)) = lower(%s)
           AND v.vet_code_statu = %s
         ORDER BY (
                SELECT count(*)
                  FROM {schema}.proje_sonda p
                 WHERE p.vet_code_ident = v.vet_code_ident
              ) DESC,
              v.vet_code_ident
         LIMIT 1
        """,
        [TYPE_PROJET_NOM, STATUT_VERSION_PRODUCTION],
    )
    ligne = cur.fetchone()

    if ligne is None:
        raise VersionProjetIntrouvableError(
            f"Aucune version en production du type « {TYPE_PROJET_NOM} » "
            "dans la base IFA : le projet ne peut pas être qualifié. "
            "Un administrateur doit renseigner IFA_PROJET_VERSION_TYPE.",
        )

    return ligne[0]


def normaliser(ligne: dict[str, Any]) -> dict[str, Any]:
    """Met la ligne écrite à la forme attendue par le plugin.

    Même règle que pour les unités (`views.normaliser_unite`) : jamais de
    `null`, que la fenêtre afficherait en toutes lettres.
    """
    return {
        "pro_code_ident": _texte(ligne["pro_code_ident"]),
        "pro_no": _texte(ligne["pro_no"]),
        "pro_nom": _texte(ligne["pro_nom"]),
        "pro_an": int(ligne["pro_an"]) if ligne["pro_an"] is not None else 0,
        "rad_no": _texte(ligne["rad_no"]),
        "pro_descr": _texte(ligne["pro_descr"]),
        "pro_com": _texte(ligne["pro_com"]),
        "pro_code_statu": _texte(ligne["pro_code_statu"]),
        "pro_date_statu": _horodatage(ligne["pro_date_statu"]),
        "pro_date_premi_mise_produ": _horodatage(ligne["pro_date_premi_mise_produ"]),
        "pro_ind_inven_norma": _texte(ligne["pro_ind_inven_norma"]) or NON,
        "pro_date_creat": _horodatage(ligne["pro_date_creat"]),
        "pro_code_utili_creat": _texte(ligne["pro_code_utili_creat"]),
    }


def normaliser_type(demande: dict[str, Any], nom: str) -> dict[str, Any]:
    """Un type associé et ce qui est planifié pour lui, pour le plugin."""
    return {
        "tue_code_ident": _texte(demande["tue_code_ident"]),
        "tue_nom": nom,
        "nb_impla_plani": _entier(demande["nb_impla_plani"]),
        "nb_remes_plani": _entier(demande["nb_remes_plani"]),
    }


def _entier(valeur: Any) -> int:
    return 0 if valeur is None else int(valeur)


def _texte(valeur: Any) -> str:
    return "" if valeur is None else str(valeur).strip()


def _horodatage(valeur: Any) -> str:
    # `timestamp without time zone` : l'heure locale de saisie, rendue telle
    # quelle, sans fuseau inventé (voir `views._horodatage`).
    if valeur is None:
        return ""
    if isinstance(valeur, datetime.datetime | datetime.date):
        return valeur.isoformat()
    return str(valeur)
